#!/usr/bin/env node
'use strict';
// Isolated archive validation: standard ZIP fixtures and deliberate corruption.
// No dependencies, network, app installation, or real chat data are used.
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const zlib = require('zlib');
const build = require('../scripts/build-release');

const root = path.resolve(__dirname, '..');
const run = path.join(root, 'test-artifacts', 'build-release-' + crypto.randomUUID());
fs.mkdirSync(run, { recursive: true });
const results = [];

function test(name, fn) {
    try { fn(); results.push({ name, pass: true }); console.log('[PASS] ' + name); }
    catch (e) { results.push({ name, pass: false, error: e.stack }); console.error('[FAIL] ' + name + ': ' + e.message); }
}

// Small independent ZIP fixture encoder; handles deflate, comments, UTF-8 and
// data descriptors, including forms not generated by the release stored fallback.
function zipFixture(entries) {
    const locals = [];
    const central = [];
    let offset = 0;
    for (const entry of entries) {
        const name = Buffer.from(entry.name);
        const bytes = Buffer.from(entry.bytes || '');
        const method = entry.method === undefined ? 8 : entry.method;
        const flags = 0x0800 | (entry.descriptor ? 8 : 0);
        const data = method === 8 ? zlib.deflateRawSync(bytes) : bytes;
        const crc = build.crc32(bytes);
        const local = Buffer.alloc(30);
        local.writeUInt32LE(0x04034b50);
        local.writeUInt16LE(20, 4); local.writeUInt16LE(flags, 6); local.writeUInt16LE(method, 8);
        if (!entry.descriptor) {
            local.writeUInt32LE(crc, 14); local.writeUInt32LE(data.length, 18); local.writeUInt32LE(bytes.length, 22);
        }
        local.writeUInt16LE(name.length, 26);
        const descriptor = entry.descriptor ? Buffer.alloc(entry.descriptor === 'unsigned' ? 12 : 16) : Buffer.alloc(0);
        if (descriptor.length) {
            const start = descriptor.length === 16 ? 4 : 0;
            if (start) descriptor.writeUInt32LE(0x08074b50);
            descriptor.writeUInt32LE(crc, start); descriptor.writeUInt32LE(data.length, start + 4); descriptor.writeUInt32LE(bytes.length, start + 8);
        }
        const c = Buffer.alloc(46);
        c.writeUInt32LE(0x02014b50); c.writeUInt16LE(0x0314, 4); c.writeUInt16LE(20, 6);
        c.writeUInt16LE(flags, 8); c.writeUInt16LE(method, 10); c.writeUInt32LE(crc, 16);
        c.writeUInt32LE(data.length, 20); c.writeUInt32LE(bytes.length, 24); c.writeUInt16LE(name.length, 28);
        c.writeUInt32LE(0x81a40000, 38); c.writeUInt32LE(offset, 42);
        locals.push(local, name, data, descriptor); central.push(c, name);
        offset += local.length + name.length + data.length + descriptor.length;
    }
    const directory = Buffer.concat(central);
    const comment = Buffer.from('fixture ZIP comment');
    const end = Buffer.alloc(22);
    end.writeUInt32LE(0x06054b50); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
    end.writeUInt32LE(directory.length, 12); end.writeUInt32LE(offset, 16); end.writeUInt16LE(comment.length, 20);
    return Buffer.concat([...locals, directory, end, comment]);
}

let next = 0;
function writeArchive(bytes) { const file = path.join(run, 'fixture-' + (++next) + '.zip'); fs.writeFileSync(file, bytes); return file; }
function centralOffset(bytes) { return bytes.indexOf(Buffer.from('504b0102', 'hex')); }
function rejects(bytes) { assert.throws(() => build.readZipFiles(writeArchive(bytes)), /ZIP 校验失败/); }

try {
    test('stored, deflate, empty and UTF-8 files decode byte-for-byte', () => {
        const entries = [{ name: 'plain.txt', bytes: 'plain', method: 0 }, { name: '中文/聊天.jsonl', bytes: '{"mes":"合成"}\n' }, { name: 'empty', bytes: '' }];
        const files = build.readZipFiles(writeArchive(zipFixture(entries)));
        assert.deepStrictEqual([...files.keys()], entries.map(e => e.name));
        for (const e of entries) assert.ok(files.get(e.name).equals(Buffer.from(e.bytes)));
    });
    test('signed and unsigned data descriptors are validated', () => {
        for (const descriptor of ['signed', 'unsigned']) {
            const bytes = zipFixture([{ name: 'a.txt', bytes: 'descriptor-content', descriptor }]);
            assert.strictEqual(build.readZipFiles(writeArchive(bytes)).get('a.txt').toString(), 'descriptor-content');
            const end = centralOffset(bytes);
            bytes[end - 8] ^= 1;
            rejects(bytes);
        }
    });
    test('path traversal, absolute and Windows redirected names are rejected', () => {
        for (const name of ['../outside', '/outside', 'a/../b', 'a//b', 'a\\b', 'C:/outside', 'a\0b']) rejects(zipFixture([{ name, bytes: 'x' }]));
    });
    test('duplicate and case-colliding names are rejected', () => {
        for (const name of ['a.txt', 'A.TXT']) rejects(zipFixture([{ name: 'a.txt' }, { name }]));
    });
    test('CRC corruption is rejected even when local and central CRC agree', () => {
        const bytes = zipFixture([{ name: 'a', bytes: 'data', method: 0 }]);
        bytes.writeUInt32LE(123, 14); bytes.writeUInt32LE(123, centralOffset(bytes) + 16);
        rejects(bytes);
    });
    test('advertised output size must match inflated bytes', () => {
        const bytes = zipFixture([{ name: 'a', bytes: 'deflated-data' }]);
        bytes.writeUInt32LE(1, 22); bytes.writeUInt32LE(1, centralOffset(bytes) + 24);
        rejects(bytes);
    });
    test('local and central file names must agree', () => {
        const bytes = zipFixture([{ name: 'a.txt', bytes: 'data' }]); bytes[30] = 98; rejects(bytes);
    });
    test('encrypted, unsupported compression and special file entries are rejected', () => {
        for (const kind of ['encrypted', 'compression', 'symlink']) {
            const bytes = zipFixture([{ name: 'a', bytes: 'data' }]);
            const c = centralOffset(bytes);
            if (kind === 'encrypted') { bytes.writeUInt16LE(0x0801, 6); bytes.writeUInt16LE(0x0801, c + 8); }
            if (kind === 'compression') { bytes.writeUInt16LE(12, 8); bytes.writeUInt16LE(12, c + 10); }
            if (kind === 'symlink') bytes.writeUInt32LE(0xa1ff0000, c + 38);
            rejects(bytes);
        }
    });
    test('truncation, central-directory count and offsets fail closed', () => {
        const original = zipFixture([{ name: 'a', bytes: 'data' }]);
        rejects(original.subarray(0, original.length - 1));
        const bytes = Buffer.from(original); bytes.writeUInt32LE(0xffffffff, centralOffset(bytes) + 42); rejects(bytes);
    });
    test('unregistered local entries and overlapping local offsets are rejected', () => {
        const bytes = zipFixture([{ name: 'a', bytes: 'one' }, { name: 'b', bytes: 'two' }]);
        const first = centralOffset(bytes);
        const second = first + 47;
        bytes.writeUInt32LE(0, second + 42); rejects(bytes);
        rejects(Buffer.concat([Buffer.from('orphan-prefix'), zipFixture([{ name: 'a', bytes: 'one' }])]));
    });

    const version = '0.0.0-synthetic';
    const snapshot = path.join(run, 'snapshot'); fs.mkdirSync(snapshot);
    const entries = build.REQUIRED.map(name => ({ name, bytes: 'synthetic ' + name }));
    entries.find(e => e.name === 'package.json').bytes = JSON.stringify({ version });
    entries.find(e => e.name === 'manifest.json').bytes = JSON.stringify({ version, display_name: 'Synthetic', js: 'client/index.js' });
    entries.find(e => e.name === 'client/manifest.json').bytes = JSON.stringify({ version });
    for (const e of entries) { const file = path.join(snapshot, e.name); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, e.bytes); }
    const names = entries.map(e => e.name);
    const verify = es => build.verifyArchive(writeArchive(zipFixture(es)), 'zip', version, names, snapshot);
    test('required metadata and exact snapshot set verify without external unzip', () => { assert.strictEqual(verify(entries).entries, entries.length); });
    test('extra and missing archive entries are rejected', () => {
        assert.throws(() => verify(entries.concat({ name: 'extra.txt', bytes: 'extra' })), /集合/);
        assert.throws(() => verify(entries.filter(e => e.name !== 'index.js')), /缺少/);
    });
    test('valid ZIP with changed file bytes fails snapshot verification', () => {
        assert.throws(() => verify(entries.map(e => e.name === 'index.js' ? { ...e, bytes: 'different' } : e)), /字节不一致/);
    });
    test('package and frontend version mismatches fail verification', () => {
        assert.throws(() => verify(entries.map(e => e.name === 'package.json' ? { ...e, bytes: '{"version":"wrong"}' } : e)), /版本/);
        assert.throws(() => verify(entries.map(e => e.name === 'client/manifest.json' ? { ...e, bytes: '{"version":"wrong"}' } : e)), /版本/);
    });
} finally {
    const summary = { total: results.length, pass: results.filter(r => r.pass).length, fail: results.filter(r => !r.pass).length };
    fs.writeFileSync(path.join(root, 'test-artifacts', 'build-release-results.json'), JSON.stringify({ summary, tests: results }, null, 2));
    console.log(JSON.stringify(summary));
    fs.rmSync(run, { recursive: true, force: true });
    process.exitCode = summary.fail ? 1 : 0;
}
